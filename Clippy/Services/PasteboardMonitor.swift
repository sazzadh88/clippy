import AppKit
import Observation

/// Reads and writes clipboard content. Pure functions over an `NSPasteboard`, so tests can use a private pasteboard.
enum PasteboardCodec {
    /// Marker types used by password managers and other apps that ask not to be recorded (nspasteboard.org).
    static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    static let maxTextBytes = 1_000_000
    static let maxImageBytes = 10_000_000

    /// Classifies the pasteboard in priority order: files, images, URLs, rich text, colors, plain text.
    /// Returns nil for content that should not be recorded.
    static func read(_ pb: NSPasteboard) -> CapturedClip? {
        let types = Set(pb.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: skippedTypes) else { return nil }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return CapturedClip(kind: .file, fileURLs: urls)
        }

        if types.contains(.png) || types.contains(.tiff) {
            // ponytail: TIFF→PNG conversion runs on the main actor; move off-main if big screenshots stutter.
            let tiffAsPNG = { pb.data(forType: .tiff).flatMap { NSBitmapImageRep(data: $0)?.representation(using: .png, properties: [:]) } }
            guard let png = pb.data(forType: .png) ?? tiffAsPNG(),
                  png.count <= maxImageBytes else { return nil }
            return CapturedClip(kind: .image, imagePNG: png)
        }

        let string = pb.string(forType: .string)
        if let url = pb.string(forType: .URL) ?? string.flatMap(webURL) {
            return CapturedClip(kind: .url, plainText: url)
        }

        if let rtf = pb.data(forType: .rtf) {
            let text = string ?? NSAttributedString(rtf: rtf, documentAttributes: nil)?.string
            guard let text = validText(text) else { return nil }
            return CapturedClip(kind: .richText, plainText: text, rtfData: rtf)
        }

        // Color before plain text: a string next to a color is just its textual form.
        if types.contains(.color), let color = NSColor(from: pb), let hex = hex(color) {
            return CapturedClip(kind: .color, plainText: hex)
        }

        if let text = validText(string) {
            return CapturedClip(kind: .text, plainText: text)
        }
        return nil
    }

    /// Writes all stored representations of `item`. Returns the resulting change count.
    @discardableResult
    static func write(_ item: ClipItem, imageData: Data?, plainTextOnly: Bool = false, to pb: NSPasteboard) -> Int {
        pb.clearContents()
        if plainTextOnly {
            let text = item.kind == .file ? item.fileURLs?.map(\.path).joined(separator: "\n") : item.plainText
            pb.setString(text ?? "", forType: .string)
            return pb.changeCount
        }
        switch item.kind {
        case .file:
            pb.writeObjects((item.fileURLs ?? []) as [NSURL])
        case .image:
            if let data = imageData {
                pb.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case .url:
            let s = item.plainText ?? ""
            pb.setString(s, forType: .URL)
            pb.setString(s, forType: .string)
        case .richText:
            if let rtf = item.rtfData { pb.setData(rtf, forType: .rtf) }
            pb.setString(item.plainText ?? "", forType: .string)
        case .text:
            pb.setString(item.plainText ?? "", forType: .string)
        case .color:
            if let hex = item.plainText, let color = color(hex: hex) { pb.writeObjects([color]) }
            pb.setString(item.plainText ?? "", forType: .string)
        }
        return pb.changeCount
    }

    // MARK: - Helpers

    static func validText(_ text: String?) -> String? {
        guard let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= maxTextBytes else { return nil }
        return text
    }

    /// A single http(s) URL with no surrounding text.
    static func webURL(_ text: String) -> String? {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(where: \.isWhitespace), let url = URL(string: t),
              ["http", "https"].contains(url.scheme?.lowercased()), url.host() != nil else { return nil }
        return t
    }

    static func hex(_ color: NSColor) -> String? {
        guard let c = color.usingColorSpace(.sRGB) else { return nil }
        let v = [c.redComponent, c.greenComponent, c.blueComponent].map { Int(($0 * 255).rounded()) }
        return String(format: "#%02X%02X%02X", v[0], v[1], v[2])
    }

    static func color(hex: String) -> NSColor? {
        guard hex.hasPrefix("#"), hex.count == 7, let v = Int(hex.dropFirst(), radix: 16) else { return nil }
        return NSColor(srgbRed: CGFloat((v >> 16) & 0xFF) / 255, green: CGFloat((v >> 8) & 0xFF) / 255,
                       blue: CGFloat(v & 0xFF) / 255, alpha: 1)
    }
}

@MainActor @Observable
final class PasteboardMonitor {
    /// True when the user set clipboard access to "Deny" in System Settings (macOS 15.4+).
    private(set) var accessDenied = false

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private let store: ClipboardStore
    @ObservationIgnored private let settings: AppSettings
    @ObservationIgnored private var lastChangeCount = 0
    @ObservationIgnored private var selfWriteChangeCount: Int?
    @ObservationIgnored private var timer: Timer?

    init(store: ClipboardStore, settings: AppSettings, pasteboard: NSPasteboard = .general) {
        self.store = store
        self.settings = settings
        self.pasteboard = pasteboard
    }

    func start() {
        lastChangeCount = pasteboard.changeCount
        // Main run loop in .common mode keeps polling during scrolling/tracking; reading
        // changeCount is a cheap integer check, so the main actor is fine.
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Puts `item` back on the pasteboard without re-recording it.
    func copy(_ item: ClipItem, plainTextOnly: Bool = false) {
        let imageData = store.imageURL(for: item).flatMap { try? Data(contentsOf: $0) }
        selfWriteChangeCount = PasteboardCodec.write(item, imageData: imageData,
                                                     plainTextOnly: plainTextOnly, to: pasteboard)
        store.bump(id: item.id) // like a fresh copy, without a duplicate
    }

    private func poll() {
        if #available(macOS 15.4, *) {
            accessDenied = pasteboard.accessBehavior == .alwaysDeny
            if accessDenied { return }
        }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != selfWriteChangeCount else { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier, settings.ignoredBundleIDs.contains(id) { return }
        guard let clip = PasteboardCodec.read(pasteboard) else { return }
        store.add(clip, sourceBundleID: app?.bundleIdentifier, sourceName: app?.localizedName)
    }
}
